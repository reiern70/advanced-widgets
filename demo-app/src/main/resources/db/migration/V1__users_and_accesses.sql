-- The accounts that may open the demos, and who opened the site when.
-- Plain SQL that PostgreSQL and H2 (in its PostgreSQL mode) both run.

CREATE TABLE users (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	-- the name of a configured account or the email a visitor registered with, in lower case
	name VARCHAR(254) NOT NULL UNIQUE,
	-- the salt and the PBKDF2 hash of the password, in Base64 separated by a colon
	password_hash VARCHAR(200) NOT NULL,
	role VARCHAR(20) NOT NULL,
	created TIMESTAMP WITH TIME ZONE NOT NULL
);

-- one row per session
CREATE TABLE accesses (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	session_id VARCHAR(100),
	-- the account signed in with, 'unknown' while nobody signed in
	user_name VARCHAR(254) NOT NULL,
	-- whether the session opened the private part, the demos
	private_part BOOLEAN NOT NULL,
	address VARCHAR(100),
	user_agent VARCHAR(500),
	accessed TIMESTAMP WITH TIME ZONE NOT NULL,
	-- the visitor's time zone and the time on the visitor's clock, as the browser tells them
	time_zone VARCHAR(100),
	local_time TIMESTAMP
);

CREATE INDEX accesses_accessed ON accesses (accessed);
