-- When an account registered on the register page expires: 6 months after registering, the daily
-- job of ExpiredAccounts deletes it with its accesses (issue #173). Accounts without it never
-- expire: administrators, configured accounts, accounts made through the API and those registered
-- before this migration, who never read that their account would be deleted.
-- Before deleting an account the job keeps a row of former_accounts, which holds nothing telling
-- who it was: no name, email, address, user agent or text typed, only what is counted.
-- Plain SQL that PostgreSQL and H2 (in its PostgreSQL mode) both run.

ALTER TABLE users ADD COLUMN expires TIMESTAMP WITH TIME ZONE;
CREATE INDEX users_expires ON users (expires);

CREATE TABLE former_accounts (
	id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	registered DATE NOT NULL,
	deleted DATE NOT NULL,
	country VARCHAR(2),
	language VARCHAR(5),
	job_role VARCHAR(20),
	accesses INTEGER NOT NULL,
	demo_accesses INTEGER NOT NULL
);
CREATE INDEX former_accounts_registered ON former_accounts (registered);
